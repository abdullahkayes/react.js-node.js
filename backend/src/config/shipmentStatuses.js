/**
 * Status Source of Truth.
 *
 * One place where the two status vocabularies are defined, because they are two
 * different things and the timeline has to show both without pretending they
 * are one sequence:
 *
 *   Shipment Request Status - where the request or booking is in its own
 *   workflow. Written by the Request & Booking flows and by staff deciding on a
 *   request. Six values.
 *
 *   Shipment Status - where the shipment is in its operational lifecycle.
 *   Twenty-four values, the same list the shipments.status column carries.
 *
 * Visibility is part of the definition, not a decoration: the command marks the
 * customer-facing values explicitly, and the timeline's visibility filter reads
 * this flag rather than re-deriving it from the wording of the status.
 *
 * Nothing here duplicates the status lists that already live in the request
 * models and the request routes. Those are what the customer-facing forms
 * validate against; this module is what the administrative timeline agrees on,
 * and where the two disagree the timeline follows this file, so a status nobody
 * can see in the tracker cannot be shown as though it were recorded.
 */

/** How a timeline entry was recorded. */
