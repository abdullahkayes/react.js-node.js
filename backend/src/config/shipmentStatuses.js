/** Every approved status, whichever type it belongs to. */
const ALL_STATUSES = [...SHIPMENT_REQUEST_STATUSES, ...SHIPMENT_STATUSES];

/**
 * The reference rows the timeline's labels table is seeded from.
 *
 * One row per approved status, carrying its system-generated label where it has
 * one. The label is what the request workflow writes; the Shipment rows have
 * none because a staff member supplies the text there.
 */
const statusReferenceRows = () =>
  [
    ...SHIPMENT_REQUEST_STATUSES.map((s) => ({
      statusType: STATUS_TYPES.REQUEST,
      status: s.status,
      label: s.label,
      visibility: s.visibility,
      isSystemLabel: true,
    })),
    ...SHIPMENT_STATUSES.map((s) => ({
      statusType: STATUS_TYPES.SHIPMENT,
      status: s.status,
      label: null,
      visibility: s.visibility,
      isSystemLabel: false,
    })),
  ];

/**
 * The system-generated label for a Shipment Request Status, or null when the
 * status is not one of the approved six.
 */
const systemLabelFor = (status) => {
  const row = SHIPMENT_REQUEST_STATUSES.find((s) => s.status === status);
  return row ? row.label : null;
};

/** The visibility of an approved status, whichever type it belongs to. */
const visibilityFor = (status) => {
  const row = ALL_STATUSES.find((s) => s.status === status);
  return row ? row.visibility : null;
};

const isCustomerFacing = (status) => visibilityFor(status) === VISIBILITY.CUSTOMER;

/** Whether a status is one the tracker is allowed to show at all. */
const isApprovedStatus = (status) => ALL_STATUSES.some((s) => s.status === status);

/** Whether a staff member may set this status through the Timeline Update modal. */
const isSelectableShipmentStatus = (status) => SHIPMENT_STATUSES.some((s) => s.status === status);

