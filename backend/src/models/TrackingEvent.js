import { Sequelize, DataTypes } from 'sequelize';
import { sequelize } from '../config/db.js';

const TrackingEvent = sequelize.define(
  'TrackingEvent',
  {
    id: { type: DataTypes.INTEGER, primaryKey: true, autoIncrement: true },
    shipmentId: { type: DataTypes.INTEGER, allowNull: false },
    // Carries both vocabularies.
    //
    // The shipment vocabulary is what new events are written with, because a
    // tracking event is read next to the shipment it belongs to and the two
    // have to say the same thing. The eight legacy values are kept because rows
    // written before the vocabulary changed are still stored with them, and
    // narrowing the column would make them unreadable.
    status: {
      type: DataTypes.ENUM(
        'pending',
        'picked_up',
        'in_transit',
        'customs',
        'out_for_delivery',
        'delivered',
        'returned',
        'Awaiting Carrier Tracking',
        'Awaiting Arrival at USA Warehouse',
        'Awaiting Arrival at Dhaka Hub',
        'Received at USA Warehouse',
        'Received at Dhaka Hub',
        'On Hold',
        'On Customs Hold',
        'On Carrier Hold',
        'In Transit to Warehouse',
        'Consolidation in Progress',
        'Shipment Locked',
        'Ready for Dispatch',
        'Shipped',
        'In International Transit',
        'Arrived at Destination Country',
        'Customs Clearance in Progress',
        'Released from Customs',
        'Sorting at Hub',
        'Out for Delivery',
        'Cancelled',
        'Disposed',
        'Seized'
      ),
      allowNull: false,
    },
    location: { type: DataTypes.STRING(255), allowNull: true },
    note: { type: DataTypes.STRING(255), allowNull: true },
    // What the timeline shows for this entry.
    //
    // label is the text a reader sees next to the status. For a status staff
    // set through the Timeline Update modal it is the text they typed; for a
    // system-generated status it is generated by the workflow that made the
    // change.
    label: { type: DataTypes.STRING(255), allowNull: true },
    // Who may see this entry. Set from the Status Source of Truth, so the
    // timeline's visibility filter reads a recorded decision rather than
    // re-deriving one from the wording of the status.
    visibility: {
      type: DataTypes.ENUM('Customer Visible', 'Internal Only'),
      allowNull: false,
      defaultValue: 'Internal Only',
    },
    // Who recorded it, as the staff reference or 'System'. The date/time is the
    // row's own createdAt, which the database sets rather than the caller.
    createdBy: { type: DataTypes.STRING(120), allowNull: true },
  },
  {
    tableName: 'tracking_events',
    timestamps: true,
    underscored: true,
  }
);

export default TrackingEvent;
